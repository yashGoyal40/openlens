import type { NamespaceScopedMetadata } from "@k8slens/kube-object";
import { KubeObject } from "@k8slens/kube-object";
import { describeResource } from "../../../resource-views/common/resource-descriptor";
import type { KubeCondition } from "../../../resource-views/common/kube-condition";

export const argoCdGroup = "argoproj.io";

export const argoApplicationsDescriptor = describeResource({
  id: "gitops-argo-cd-applications",
  kind: "Application",
  group: argoCdGroup,
  versions: ["v1alpha1"],
  apiName: "applications",
  namespaced: true,
  title: "Applications",
});

export const argoApplicationSetsDescriptor = describeResource({
  id: "gitops-argo-cd-application-sets",
  kind: "ApplicationSet",
  group: argoCdGroup,
  versions: ["v1alpha1"],
  apiName: "applicationsets",
  namespaced: true,
  title: "Application Sets",
});

export const argoAppProjectsDescriptor = describeResource({
  id: "gitops-argo-cd-app-projects",
  kind: "AppProject",
  group: argoCdGroup,
  versions: ["v1alpha1"],
  apiName: "appprojects",
  namespaced: true,
  title: "Projects",
});

export type ArgoSyncStatusCode = "Synced" | "OutOfSync" | "Unknown";

export type ArgoHealthStatusCode = "Healthy" | "Progressing" | "Degraded" | "Suspended" | "Missing" | "Unknown";

export type ArgoOperationPhase = "Running" | "Terminating" | "Failed" | "Error" | "Succeeded";

export interface ArgoApplicationSource {
  repoURL: string;
  path?: string;
  chart?: string;
  targetRevision?: string;

  /**
   * Name of the source, used to reference it from other sources of a multi source application
   */
  ref?: string;
  name?: string;
  helm?: {
    releaseName?: string;
    valueFiles?: string[];
  };
  kustomize?: Record<string, unknown>;
  directory?: Record<string, unknown>;
  plugin?: { name?: string };
}

export interface ArgoApplicationDestination {
  server?: string;
  name?: string;
  namespace?: string;
}

export interface ArgoSyncPolicy {
  automated?: {
    prune?: boolean;
    selfHeal?: boolean;
    allowEmpty?: boolean;
    enabled?: boolean;
  };
  syncOptions?: string[];
  retry?: {
    limit?: number;
  };
}

export interface ArgoApplicationSpec {
  project: string;
  source?: ArgoApplicationSource;
  sources?: ArgoApplicationSource[];
  destination: ArgoApplicationDestination;
  syncPolicy?: ArgoSyncPolicy;
  revisionHistoryLimit?: number;
}

/**
 * The status of a single resource managed by an application, or of an application generated by an application set
 */
export interface ArgoResourceStatus {
  group?: string;
  version?: string;
  kind: string;
  namespace?: string;
  name: string;
  status?: ArgoSyncStatusCode | string;
  health?: {
    status?: ArgoHealthStatusCode | string;
    message?: string;
  };
  hook?: boolean;
  requiresPruning?: boolean;
  syncWave?: number;
}

/**
 * Argo CD conditions only describe problems and are not `metav1.Condition` shaped
 */
export interface ArgoApplicationCondition {
  type: string;
  message: string;
  lastTransitionTime?: string;
}

export interface ArgoRevisionHistory {
  id: number;
  revision?: string;
  revisions?: string[];
  deployedAt: string;
  deployStartedAt?: string;
  source?: ArgoApplicationSource;
  sources?: ArgoApplicationSource[];
}

export interface ArgoOperationState {
  phase: ArgoOperationPhase | string;
  message?: string;
  startedAt: string;
  finishedAt?: string;
  retryCount?: number;
  syncResult?: {
    revision?: string;
    revisions?: string[];
  };
}

export interface ArgoApplicationStatus {
  resources?: ArgoResourceStatus[];
  sync?: {
    status: ArgoSyncStatusCode | string;
    revision?: string;
    revisions?: string[];
  };
  health?: {
    status?: ArgoHealthStatusCode | string;
    message?: string;
    lastTransitionTime?: string;
  };
  history?: ArgoRevisionHistory[];
  conditions?: ArgoApplicationCondition[];
  reconciledAt?: string;
  operationState?: ArgoOperationState;
  sourceType?: string;
  sourceTypes?: string[];
  summary?: {
    externalURLs?: string[];
    images?: string[];
  };
  controllerNamespace?: string;
}

export class ArgoApplication extends KubeObject<NamespaceScopedMetadata, ArgoApplicationStatus, ArgoApplicationSpec> {
  static readonly kind = argoApplicationsDescriptor.kind;
  static readonly namespaced = argoApplicationsDescriptor.namespaced;
  static readonly apiBase = argoApplicationsDescriptor.apiBase;
}

/**
 * A generator is an object with a single key naming its type, e.g. `{ git: {...} }`, plus an optional `selector`
 */
export type ArgoApplicationSetGenerator = Partial<Record<string, unknown>> & {
  matrix?: { generators?: ArgoApplicationSetGenerator[] };
  merge?: { generators?: ArgoApplicationSetGenerator[]; mergeKeys?: string[] };
  selector?: unknown;
};

export interface ArgoApplicationSetSpec {
  generators: ArgoApplicationSetGenerator[];
  template: {
    metadata: {
      name?: string;
      namespace?: string;
    };
    spec: Partial<ArgoApplicationSpec>;
  };
  goTemplate?: boolean;
  syncPolicy?: {
    preserveResourcesOnDeletion?: boolean;
    applicationsSync?: "create-only" | "create-update" | "create-delete" | "sync" | string;
  };
  strategy?: {
    type?: "AllAtOnce" | "RollingSync" | string;
    rollingSync?: {
      steps?: unknown[];
    };
  };
}

export interface ArgoApplicationSetApplicationStatus {
  application: string;
  status: string;
  message?: string;
  step?: string;
  lastTransitionTime?: string;
}

export interface ArgoApplicationSetStatus {
  /**
   * Unlike those of applications, application set conditions are `metav1.Condition` shaped
   */
  conditions?: KubeCondition[];
  resources?: ArgoResourceStatus[];
  resourcesCount?: number;
  applicationStatus?: ArgoApplicationSetApplicationStatus[];
}

export class ArgoApplicationSet extends KubeObject<NamespaceScopedMetadata, ArgoApplicationSetStatus, ArgoApplicationSetSpec> {
  static readonly kind = argoApplicationSetsDescriptor.kind;
  static readonly namespaced = argoApplicationSetsDescriptor.namespaced;
  static readonly apiBase = argoApplicationSetsDescriptor.apiBase;
}

export interface ArgoGroupKind {
  group: string;
  kind: string;
}

export interface ArgoProjectRole {
  name: string;
  description?: string;
  policies?: string[];
  groups?: string[];
  jwtTokens?: unknown[];
}

export interface ArgoSyncWindow {
  kind: "allow" | "deny" | string;
  schedule: string;
  duration: string;
  applications?: string[];
  namespaces?: string[];
  clusters?: string[];
  manualSync?: boolean;
  timeZone?: string;
}

export interface ArgoAppProjectSpec {
  description?: string;
  sourceRepos?: string[];
  sourceNamespaces?: string[];
  destinations?: ArgoApplicationDestination[];
  clusterResourceWhitelist?: ArgoGroupKind[];
  clusterResourceBlacklist?: ArgoGroupKind[];
  namespaceResourceWhitelist?: ArgoGroupKind[];
  namespaceResourceBlacklist?: ArgoGroupKind[];
  roles?: ArgoProjectRole[];
  syncWindows?: ArgoSyncWindow[];
  signatureKeys?: { keyID: string }[];
}

export class ArgoAppProject extends KubeObject<NamespaceScopedMetadata, unknown, ArgoAppProjectSpec> {
  static readonly kind = argoAppProjectsDescriptor.kind;
  static readonly namespaced = argoAppProjectsDescriptor.namespaced;
  static readonly apiBase = argoAppProjectsDescriptor.apiBase;
}
